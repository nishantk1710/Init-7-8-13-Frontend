import type { ReactNode } from "react"

import {
  AGING_BAND_LABEL,
  EXCEPTION_STATUS_LABEL,
  EXCEPTION_STATUS_ORDER,
  EXCEPTION_TYPE_LABEL,
  PLAN_STATUS_LABEL,
  PLAN_STATUS_ORDER,
} from "@/features/initiative-13/utils/status-labels"
import { EMPTY_LABEL } from "@/features/initiative-13/utils/empty-labels"
import { formatApiDate, formatApiDateTime } from "@/lib/api/format"
import type { SummaryReport } from "@/lib/api/i13-report"
import { cn, formatCount } from "@/lib/utils"

/**
 * One saved summary report, laid out as a document.
 *
 * The same component renders on screen and in the PDF (see
 * `summary-report-print.tsx`), so the download is always the page the reader
 * was looking at. No hooks and no client APIs: it is pure layout over the saved
 * report, and nothing here recomputes a figure — every number is read from
 * `report.facts` as the backend stored it.
 *
 * Status codes are shown through the screens' own label maps, so "Non-AI" and
 * "Requester not identified" read the same here as on the dashboard.
 */

const NOT_RECORDED = EMPTY_LABEL.notRecorded.label

function label(map: Record<string, string>, code: string): string {
  return map[code] ?? code
}

function count(value: number | null | undefined): string {
  return value == null ? NOT_RECORDED : formatCount(value)
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="report-section flex flex-col gap-2">
      <h2 className="text-sm font-semibold text-foreground">{title}</h2>
      {children}
    </section>
  )
}

function Stat({ label: name, value, hint }: { label: string; value: string; hint?: string }) {
  return (
    <div className="report-stat flex flex-col gap-1 rounded-lg border border-border bg-card p-3">
      <div className="text-xs text-muted-foreground">{name}</div>
      <div className="text-xl font-semibold text-foreground">{value}</div>
      {hint && <div className="text-xs text-muted-foreground">{hint}</div>}
    </div>
  )
}

function Table({ headers, rows }: { headers: string[]; rows: ReactNode[][] }) {
  return (
    <div className="overflow-x-auto rounded-lg border border-border">
      <table className="report-table w-full text-left text-xs">
        <thead className="bg-muted/50 text-muted-foreground">
          <tr>
            {headers.map((h) => (
              <th key={h} className="px-3 py-2 font-medium">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className="border-t border-border">
              {row.map((cell, j) => (
                <td key={j} className="px-3 py-2 align-top text-foreground">
                  {cell ?? NOT_RECORDED}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="flex list-disc flex-col gap-1.5 pl-5 text-sm text-foreground">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  )
}

export function SummaryReportDocument({ report, className }: { report: SummaryReport; className?: string }) {
  const { facts, narrative } = report
  const pos = facts.positions
  const grni = facts.gr_not_issued
  const exc = facts.exceptions
  const aiWritten = narrative.source === "MODEL"

  return (
    <article className={cn("report-document flex flex-col gap-6", className)}>
      <header className="report-cover flex flex-col gap-3 border-b border-border pb-4">
        <div>
          <p className="text-xs uppercase tracking-wide text-muted-foreground">OAR Utilization · Summary report</p>
          <h2 className="mt-1 text-lg font-semibold text-foreground">{facts.scope.label}</h2>
        </div>
        <dl className="grid grid-cols-2 gap-x-6 gap-y-1 text-xs sm:grid-cols-4">
          <div>
            <dt className="text-muted-foreground">Data as of</dt>
            <dd className="text-foreground">{formatApiDate(facts.data_as_of)}</dd>
          </div>
          <div>
            <dt className="text-muted-foreground">Generated</dt>
            <dd className="text-foreground">{formatApiDateTime(report.generatedAt)}</dd>
          </div>
          <div>
            <dt className="text-muted-foreground">Generated by</dt>
            <dd className="text-foreground">{report.generatedBy || NOT_RECORDED}</dd>
          </div>
          <div>
            <dt className="text-muted-foreground">Wording</dt>
            <dd className="text-foreground">{aiWritten ? "AI-written from the figures below" : "Standard wording"}</dd>
          </div>
        </dl>
        {narrative.notes.length > 0 && (
          <p className="text-xs text-muted-foreground">{narrative.notes.join(" ")}</p>
        )}
      </header>

      <p className="report-headline rounded-lg border-l-4 border-primary bg-muted/40 px-4 py-3 text-base font-medium text-foreground">
        {narrative.headline}
      </p>

      <div className="report-stats grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
        <Stat label="OAR materials" value={count(pos.total)} />
        <Stat
          label="Non-moving"
          value={count(pos.NON_MOVING)}
          hint={pos.non_moving_pct == null ? undefined : `${pos.non_moving_pct}% of OAR materials`}
        />
        <Stat label="Planned Overdue" value={count(facts.plans.plan_breach_count)} />
        <Stat label="Non-AI" value={count(facts.plans.no_plan_count)} />
        <Stat
          label="Received not issued"
          value={count(grni.open_line_count)}
          hint={`Reservation lines, ${grni.threshold_days}+ days`}
        />
        <Stat label="Open procurement exceptions" value={count(exc.unresolved)} hint={`of ${count(exc.total)}`} />
      </div>

      <Section title="Key findings">
        <Bullets items={narrative.findings} />
      </Section>

      {narrative.risks.length > 0 && (
        <Section title="Risks">
          <Bullets items={narrative.risks} />
        </Section>
      )}

      {narrative.actions.length > 0 && (
        <Section title="Recommended actions">
          <Table
            headers={["#", "Action", "Owner"]}
            rows={narrative.actions.map((a, i) => [i + 1, a.action, a.owner])}
          />
        </Section>
      )}

      <div className="grid gap-6 lg:grid-cols-2">
        <Section title="Stock type and plan coverage">
          <Table
            headers={["Measure", "OAR materials"]}
            rows={[
              ...(["FAST", "SLOW", "NON_MOVING"] as const).map((band) => [
                label(AGING_BAND_LABEL, band),
                count(pos[band]),
              ]),
              ...PLAN_STATUS_ORDER.map((status) => [
                `Acquired vs plan: ${label(PLAN_STATUS_LABEL, status)}`,
                count(facts.plans.acquired_vs_plan[status]),
              ]),
            ]}
          />
        </Section>
        <Section title="Procurement exceptions by status">
          <Table
            headers={["Status", "Exceptions"]}
            rows={EXCEPTION_STATUS_ORDER.map((status) => [
              label(EXCEPTION_STATUS_LABEL, status),
              count(exc.by_status[status]),
            ])}
          />
        </Section>
      </div>

      {grni.longest_waiting.length > 0 && (
        <Section title="Longest-waiting received, not issued">
          <Table
            headers={["Material", "Plant", "Reservation", "PO", "Outstanding qty", "Days since GR"]}
            rows={grni.longest_waiting.map((g) => [
              g.description ? `${g.description} (${g.material})` : g.material,
              g.plant,
              g.reservation,
              g.po_number ?? EMPTY_LABEL.noPoLinked.label,
              count(g.outstanding_quantity),
              count(g.days_since_gr),
            ])}
          />
        </Section>
      )}

      {exc.oldest_unresolved.length > 0 && (
        <Section title="Longest-open procurement exceptions">
          <Table
            headers={["Material", "Plant", "Reservation", "Type", "Status", "Days open"]}
            rows={exc.oldest_unresolved.map((e) => [
              e.description ? `${e.description} (${e.material})` : e.material,
              e.plant,
              e.reservation ?? EMPTY_LABEL.noReservationLinked.label,
              label(EXCEPTION_TYPE_LABEL, e.type),
              label(EXCEPTION_STATUS_LABEL, e.status),
              count(e.days_open),
            ])}
          />
        </Section>
      )}

      <footer className="report-footer border-t border-border pt-3 text-xs text-muted-foreground">
        Every figure is calculated by the system from SAP data and matches the OAR Utilization screens as of{" "}
        {formatApiDate(facts.data_as_of)}.{" "}
        {aiWritten
          ? `The wording was written by AI${narrative.model ? ` (${narrative.model})` : ""} from those figures and checked to contain no other numbers.`
          : "The wording is the system's standard text."}
        {facts.valuation_is_mocked && " Stock valuation is not yet live, so no money values are shown."}
      </footer>
    </article>
  )
}
